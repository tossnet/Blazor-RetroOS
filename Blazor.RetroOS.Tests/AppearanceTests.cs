using System.Text.RegularExpressions;
using Blazor.RetroOS.Components;
using Bunit;
using Microsoft.AspNetCore.Components;
using Xunit;

namespace Blazor.RetroOS.Tests;

// The Appearance parameter adds the retro-appearance-<os> class on the root element of a component.
public class AppearanceParameterTests : TestContext
{
    public static TheoryData<Appearance> Appearances => new(Enum.GetValues<Appearance>());

    // Root element of each component, rendered with the given appearance (null = parameter not set).
    private IEnumerable<(string Name, AngleSharp.Dom.IElement Root)> RenderAll(Appearance? appearance)
    {
        yield return ("Button", RenderComponent<RetroButton>(p => p.Add(x => x.Appearance, appearance)).Find(".retro-button"));
        yield return ("CheckBox", RenderComponent<RetroCheckBox>(p => p.Add(x => x.Appearance, appearance)).Find(".retro-checkbox"));
        yield return ("TextBox", RenderComponent<RetroTextBox>(p => p.Add(x => x.Appearance, appearance)).Find(".retro-field"));
        yield return ("ProgressBar", RenderComponent<RetroProgressBar>(p => p.Add(x => x.Appearance, appearance)).Find(".retro-progress"));
        yield return ("Window", RenderComponent<RetroWindow>(p => p.Add(x => x.Appearance, appearance)).Find(".retro-window"));
        yield return ("Screen", RenderComponent<RetroScreen>(p => p.Add(x => x.Appearance, appearance)).Find(".retro-screen"));
    }

    [Theory]
    [MemberData(nameof(Appearances))]
    public void EveryComponent_RendersTheAppearanceClassOnItsRoot(Appearance appearance)
    {
        Assert.All(RenderAll(appearance), c =>
            Assert.True(c.Root.ClassList.Contains(appearance.ToCssClass()), $"{c.Name}: {c.Root.ClassName}"));
    }

    [Fact]
    public void WithoutAppearance_NoAppearanceClass()
    {
        Assert.All(RenderAll(null), c =>
            Assert.DoesNotContain("retro-appearance-", c.Root.ClassName));
    }

    [Fact]
    public void AppearanceClass_IsBeforeTheUserClass()
    {
        var cut = RenderComponent<RetroButton>(p => p
            .Add(x => x.Default, true)
            .Add(x => x.Appearance, Appearance.AtariST)
            .Add(x => x.Class, "mine"));

        Assert.Equal("retro-button retro-button-default retro-appearance-atarist mine", cut.Find("button").ClassName);
    }

    [Fact]
    public void ChangingAppearance_SwapsTheClass()
    {
        var cut = RenderComponent<RetroWindow>(p => p.Add(x => x.Appearance, Appearance.Amiga13));
        Assert.Contains("retro-appearance-amiga13", cut.Find(".retro-window").ClassName);

        cut.SetParametersAndRender(p => p.Add(x => x.Appearance, Appearance.AtariST));

        var cls = cut.Find(".retro-window").ClassName;
        Assert.Contains("retro-appearance-atarist", cls);
        Assert.DoesNotContain("retro-appearance-amiga13", cls);
    }

    // The children take the look of their parent through CSS (@scope): no class on them.
    [Fact]
    public void Children_DoNotRepeatTheAppearanceClass()
    {
        var cut = RenderComponent<RetroWindow>(p => p
            .Add(x => x.Appearance, Appearance.AtariST)
            .AddChildContent<RetroButton>(b => b.AddChildContent("OK")));

        Assert.Single(cut.FindAll(".retro-appearance-atarist"));
        Assert.DoesNotContain("retro-appearance-", cut.Find(".retro-button").ClassName);
    }

    [Theory]
    [InlineData(Appearance.Amiga13, "amiga13")]
    [InlineData(Appearance.AtariST, "atarist")]
    public void Extensions_AreConsistent(Appearance appearance, string key)
    {
        Assert.Equal(key, appearance.ToKey());
        Assert.Equal($"retroos-{key}.css", appearance.ToFileName());
        Assert.Equal($"retro-appearance-{key}", appearance.ToCssClass());
        Assert.Equal($"_content/BlazorRetroOS/css/retroos-{key}.css", appearance.ToStylesheetPath());
    }

    [Fact]
    public void BundlePath_PointsToThePackageContent()
    {
        Assert.Equal("_content/BlazorRetroOS/css/retroos.css", AppearanceExtensions.BundlePath);
    }
}

// retroos.css is generated by the build (StaticDist.targets) from the retroos-<os>.css files.
public class BundleTests
{
    private static readonly string Bundle = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Themes", "retroos.css"));

    public static TheoryData<Appearance> Appearances => new(Enum.GetValues<Appearance>());

    private static string ScopeHeader(Appearance appearance)
    {
        foreach (Match m in Regex.Matches(Bundle, @"@scope \(([^)]*)\)(?: to \(([^)]*)\))? \{"))
        {
            var roots = m.Groups[1].Value.Split(',', StringSplitOptions.TrimEntries);
            if (roots.Contains("." + appearance.ToCssClass()))
                return m.Value;
        }
        return "";
    }

    [Theory]
    [MemberData(nameof(Appearances))]
    public void EveryAppearance_HasItsScope_LimitedByTheOthers(Appearance appearance)
    {
        var header = ScopeHeader(appearance);
        Assert.False(header.Length == 0, $"No @scope for {appearance.ToCssClass()}");

        foreach (var other in Enum.GetValues<Appearance>().Where(a => a != appearance))
            Assert.Contains("." + other.ToCssClass(), Regex.Match(header, @" to \(([^)]*)\)").Groups[1].Value);
    }

    // The first value of the enum is the default appearance: also scoped to :root,
    // so that components without Appearance are styled.
    [Fact]
    public void DefaultAppearance_IsTheFirstEnumValue()
    {
        var first = Enum.GetValues<Appearance>()[0];

        Assert.Contains(":root", ScopeHeader(first));
        Assert.Single(Regex.Matches(Bundle, @"@scope \([^)]*:root"));
    }

    [Fact]
    public void Variables_AreDefinedOnTheScopeRoot()
    {
        var withoutComments = Regex.Replace(Bundle, @"/\*[\s\S]*?\*/", "");
        Assert.DoesNotMatch(@":root\s*\{", withoutComments);
        Assert.Equal(Enum.GetValues<Appearance>().Length, Regex.Matches(withoutComments, @":scope\s*\{").Count);
    }

    [Fact]
    public void Bundle_ContainsEveryRuleOfEveryAppearance()
    {
        foreach (var appearance in Enum.GetValues<Appearance>())
        {
            var source = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Themes", appearance.ToFileName())).Replace("\r\n", "\n").TrimEnd();
            Assert.Contains("/* --- " + appearance.ToFileName() + " --- */", Bundle);
            // The declarations of the last rule of the source are copied as they are.
            var lastDeclarations = source[source.LastIndexOf('{')..];
            Assert.Contains(lastDeclarations, Bundle);
        }
    }

    // Inside @scope, a selector without :scope does not match the scope root itself
    // (e.g. a RetroButton with its own Appearance): every selector must contain it.
    [Fact]
    public void EverySelector_CanMatchTheScopeRoot()
    {
        var css = Regex.Replace(Bundle, @"/\*[\s\S]*?\*/", "");
        var selectors = Regex.Matches(css, @"(?<=[{};]\s*)([^{};@]+?)\s*\{")
            .SelectMany(m => m.Groups[1].Value.Split(",\n"))
            .Select(s => s.Trim())
            .ToList();

        Assert.NotEmpty(selectors);
        var missing = selectors.Where(s => !s.Contains(":scope")).ToList();
        Assert.True(missing.Count == 0, "Without :scope: " + string.Join(" | ", missing));
    }

    [Fact]
    public void PseudoElements_StayAtTheEndOfTheirSelector()
    {
        Assert.Contains(".retro-gadget:where(:scope, *)::before", Bundle);
        Assert.DoesNotContain("::before:where", Bundle);
        Assert.DoesNotContain("::after:where", Bundle);
    }
}
